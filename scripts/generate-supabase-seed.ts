/*
 * Builds supabase/seed.sql from the site's own product and delivery config, so
 * the database starts out exactly like the current website.
 *
 *   npx tsx scripts/generate-supabase-seed.ts
 *
 * The seed only inserts rows that don't exist yet (ON CONFLICT DO NOTHING), so
 * running it again never overwrites prices, stock or edits made in the admin app.
 * Stock starts as NULL ("not tracked") for every size: nothing sells out until
 * you enter real counts.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import {
  PRODUCTS,
  getCategoryNameHebrew,
  getTranslatedAllergens,
  getTranslatedIngredients,
  getTranslatedProductDescription,
  getTranslatedProductName,
  getTranslatedProductTagline,
} from "../client/src/config/products";
import { deliveryZones, zoneName } from "../client/src/config/deliveryZones";

const q = (v: string | null | undefined) => (v == null || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));
const b = (v: boolean) => (v ? "true" : "false");
const j = (v: unknown) => (v == null ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const orNull = (en: string, he: string) => (he && he !== en ? he : null);

const out: string[] = [];
out.push(
  "-- Generated by scripts/generate-supabase-seed.ts from client/src/config. Do not edit by hand:",
  "-- change the config (or the database) and regenerate. Safe to run more than once.",
  "",
  "begin;",
  ""
);

out.push("-- Delivery zones");
deliveryZones.forEach((z, i) => {
  const fee = z.price < 0 ? null : z.price;
  const min = 0; // no minimum order (business owner, 2026-11-25)
  out.push(
    `insert into public.delivery_zones (id, name_en, name_he, fee, min_order, sort_order) values (${q(z.id)}, ${q(z.name)}, ${q(zoneName(z, "he"))}, ${n(fee)}, ${min}, ${i * 10}) on conflict (id) do nothing;`
  );
});
out.push("");

PRODUCTS.forEach((cat, ci) => {
  out.push(`-- ${cat.name}`);
  const catHe = getCategoryNameHebrew(cat.name.toUpperCase());
  out.push(
    `insert into public.categories (id, name_en, name_he, description_en, image, sort_order) values (${q(cat.id)}, ${q(cat.name)}, ${q(orNull(cat.name, catHe))}, ${q(cat.description)}, ${q(cat.image)}, ${ci * 10}) on conflict (id) do nothing;`
  );

  cat.variants.forEach((v, vi) => {
    const nameHe = getTranslatedProductName(v.id, "he");
    const descHe = getTranslatedProductDescription(v.id, "he");
    const tagHe = getTranslatedProductTagline(v.id, "he");
    out.push(
      `insert into public.products (id, category_id, name_en, name_he, description_en, description_he, tagline_en, tagline_he, image, spice_level, is_kosher, is_available, unavailable_reason, nutrition, ingredients_en, ingredients_he, allergens_en, allergens_he, sort_order) values (` +
        [
          q(v.id),
          q(cat.id),
          q(v.name),
          q(orNull(v.name, nameHe)),
          q(v.description),
          q(orNull(v.description, descHe)),
          q(v.tagline),
          q(orNull(v.tagline, tagHe)),
          q(v.image),
          n(v.spiceLevel),
          b(v.isKosher),
          b(v.isAvailable !== false),
          q(v.unavailableReason),
          j(v.nutrition),
          q(getTranslatedIngredients(v.id, "en") || v.ingredients),
          q(getTranslatedIngredients(v.id, "he")),
          q(getTranslatedAllergens(v.id, "en") || v.allergens),
          q(getTranslatedAllergens(v.id, "he")),
          vi * 10,
        ].join(", ") +
        `) on conflict (id) do nothing;`
    );
    v.sizes.forEach((s, si) => {
      out.push(
        `insert into public.product_sizes (product_id, label, weight, price, stock, sort_order) values (${q(v.id)}, ${q(s.size)}, ${q(s.weight)}, ${n(s.price)}, null, ${si * 10}) on conflict (product_id, label) do nothing;`
      );
    });
  });
  out.push("");
});

out.push("commit;", "");

const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "supabase", "seed.sql");
writeFileSync(target, out.join("\n"), "utf8");
const sizes = PRODUCTS.reduce((a, c) => a + c.variants.reduce((b2, v) => b2 + v.sizes.length, 0), 0);
console.log(`Wrote ${target}: ${deliveryZones.length} zones, ${PRODUCTS.length} categories, ${PRODUCTS.reduce((a, c) => a + c.variants.length, 0)} products, ${sizes} sizes`);

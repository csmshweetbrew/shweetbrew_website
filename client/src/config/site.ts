export function getWhatsAppLink(message?: string): string {
  const encoded = message ? encodeURIComponent(message) : "";
  return `https://wa.me/${SITE_CONFIG.contact.whatsapp.replace(/[^\d]/g, "")}${message ? `?text=${encoded}` : ""}`;
}

